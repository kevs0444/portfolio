import { mkdir, readdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const repoRoot = process.cwd();
const vaultRoot = path.join(repoRoot, "Portfolio");
const outputPath = path.join(repoRoot, "app", "data", "generated-knowledge.ts");

const SKIP_DIRS = new Set([".obsidian", "_Templates", "99-Private"]);

async function dirExists(dirPath) {
  try {
    return (await stat(dirPath)).isDirectory();
  } catch {
    return false;
  }
}

async function collectMarkdownFiles(dirPath) {
  const entries = await readdir(dirPath, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (SKIP_DIRS.has(entry.name)) continue;
    const full = path.join(dirPath, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectMarkdownFiles(full)));
    } else if (entry.isFile() && entry.name.endsWith(".md")) {
      files.push(full);
    }
  }
  return files;
}

function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) {
    return { meta: {}, body: raw };
  }

  const meta = {};
  for (const line of match[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!kv) continue;
    const key = kv[1].trim();
    let val = kv[2].trim();
    if (val === "true") {
      meta[key] = true;
    } else if (val === "false") {
      meta[key] = false;
    } else if (/^-?\d+(\.\d+)?$/.test(val)) {
      meta[key] = Number(val);
    } else {
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        try {
          val = val.startsWith('"') ? JSON.parse(val) : val.slice(1, -1);
        } catch {
          val = val.slice(1, -1);
        }
      }
      meta[key] = val;
    }
  }

  return { meta, body: match[2] };
}

function cleanBodyForPrompt(body) {
  const lines = body.split(/\r?\n/);
  const cleaned = [];

  for (const line of lines) {
    // Exclude Obsidian navigation footer lines from the AI prompt
    if (/^\s*Related:\s*\[\[/.test(line)) continue;
    // Drop top-level H1 markdown heading lines if redundant, or turn headings into clean labels
    if (/^\s*#\s+/.test(line)) continue;
    let out = line.replace(/^#{2,6}\s+/, "");
    // Convert Obsidian [[Target|Alias]] -> Alias and [[Target]] -> Target
    out = out.replace(/\[\[([^|\]]+)\|([^\]]+)\]\]/g, "$2");
    out = out.replace(/\[\[([^\]]+)\]\]/g, "$1");
    // Strip Markdown bold/italic markers so Bop AI sees clean plain text
    out = out.replace(/\*\*([^*]+)\*\*/g, "$1").replace(/__([^_]+)__/g, "$1");
    cleaned.push(out);
  }

  return cleaned.join("\n").replace(/\n{3,}/g, "\n\n").trim();
}

async function main() {
  if (!(await dirExists(vaultRoot))) {
    throw new Error(`Obsidian vault directory not found at ${vaultRoot}`);
  }

  const mdFiles = await collectMarkdownFiles(vaultRoot);
  const included = [];

  for (const filePath of mdFiles) {
    const raw = await readFile(filePath, "utf8");
    const { meta, body } = parseFrontmatter(raw);
    if (meta.bop_ai !== true) continue;

    const text = cleanBodyForPrompt(body);
    if (!text) continue;

    included.push({
      relPath: path.relative(vaultRoot, filePath).replace(/\\/g, "/"),
      order: typeof meta.bop_order === "number" ? meta.bop_order : 9999,
      text,
    });
  }

  included.sort((a, b) => {
    if (a.order !== b.order) return a.order - b.order;
    return a.relPath.localeCompare(b.relPath);
  });

  const compiledKnowledge = `\n${included.map((item) => item.text).join("\n\n")}\n`;

  await mkdir(path.dirname(outputPath), { recursive: true });
  const tsContent = `// AUTO-GENERATED BY scripts/sync-brain.mjs FROM Portfolio/ — DO NOT EDIT MANUALLY.
const RAW_KNOWLEDGE = ${JSON.stringify(compiledKnowledge)};

export function buildKnowledgeBase(portfolioUrl: string): string {
  return RAW_KNOWLEDGE.replaceAll("{{SITE_URL}}", portfolioUrl);
}
`;
  await writeFile(outputPath, tsContent, "utf8");
  console.log(`Compiled ${included.length} Obsidian notes into ${path.relative(repoRoot, outputPath)}`);
}

main().catch((error) => {
  console.error("Failed to compile Obsidian knowledge base:", error);
  process.exit(1);
});
